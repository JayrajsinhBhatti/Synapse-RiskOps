"""
Synapse RiskOps - Conformal Risk Intervals Calibrator
=====================================================
Owner: RiskOps ML Core
Method: Split Conformal Prediction (Inductive Conformal Prediction)

Overview:
---------
Quantifies prediction uncertainty for risk scores generated by the Synapse RiskOps
RiskEngine. Rather than relying on heuristic or uncalibrated confidence intervals,
this module uses Split Conformal Prediction to produce risk bounds [lower, upper]
with rigorous finite-sample coverage guarantees under exchangeability.

Mathematical Formulation:
--------------------------
Given a held-out calibration set D_cal = {(x_i, y_i)}_{i=1}^n where:
  - x_i is the telemetry feature snapshot for service i
  - y_i in [0, 100] is the ground-truth operational risk outcome
  - \hat{y}_i = RiskEngine(x_i) in [0, 100] is the point prediction

1. Nonconformity Score:
   We use the absolute residual nonconformity score:
     R_i = |y_i - \hat{y}_i|
   which measures the deviation between predicted risk and actual operational risk.

2. Conformal Quantile:
   For target coverage 1 - \alpha (e.g. \alpha = 0.10 for 90% coverage),
   the conformal cutoff \hat{q} is computed as:
     k = min(n, ceil((n + 1) * (1 - \alpha)))
     \hat{q} = R_{(k)}  (the k-th order statistic of R_1, ..., R_n)

3. Prediction Interval for New Instance x_{n+1}:
   Given a point estimate \hat{y}_{n+1}:
     lower = max(0.0, round(\hat{y}_{n+1} - \hat{q}, 2))
     upper = min(100.0, round(\hat{y}_{n+1} + \hat{q}, 2))
     interval_width = round(upper - lower, 2)

Assumptions & Validity Conditions:
----------------------------------
1. Exchangeability:
   The held-out calibration samples and future operational test samples must be
   exchangeable (e.g. drawn from the same joint distribution P(X, Y)).
   Under this assumption, the marginal coverage satisfies:
     P(Y_{n+1} in [lower, upper]) >= 1 - \alpha.

2. Stationary Operating Conditions:
   Calibration assumes baseline system telemetry characteristics remain stationary.
   During severe distribution shifts, unobserved chaos experiments, or novel cascade
   failures, empirical coverage may drift from nominal coverage.

3. Scope and Interpretation Limitation:
   The conformal risk interval quantifies statistical uncertainty in the risk score
   estimate. It does NOT represent the probability that a catastrophic system failure
   or crash will occur.
   Do NOT present a [65, 85] interval as an "85% failure probability".

Calibration Requirements & Edge Cases:
--------------------------------------
- Minimum Samples: At least 30 held-out calibration samples (n >= 30) are required.
  If n < 30 or uncalibrated, the calibrator explicitly reports status='insufficient_data'
  or status='uncalibrated' with lower=None, upper=None, and is_calibrated=False.
  No fabricated bounds are returned.
"""

import math
from typing import Dict, List, Optional, Tuple, Union, Any
from datetime import datetime, timezone
import numpy as np
import pandas as pd
from loguru import logger

from app.schemas.prediction import ConformalInterval


class ConformalCalibrator:
    """
    Split Conformal Prediction Calibrator for RiskOps Risk Scores.
    """

    MIN_CALIBRATION_SAMPLES: int = 30
    DEFAULT_TARGET_COVERAGE: float = 0.90
    METHOD_NAME: str = "split_conformal_residual"

    ASSUMPTION_NOTE: str = (
        "Finite-sample >= 1-alpha marginal coverage holds under exchangeability "
        "between held-out calibration data and production telemetry. "
        "Quantifies risk score estimation uncertainty; does NOT represent probability of failure."
    )

    def __init__(self, min_samples: int = MIN_CALIBRATION_SAMPLES):
        self.min_samples = min_samples
        self.is_calibrated: bool = False
        self.status: str = "uncalibrated"
        self.calibration_samples: int = 0
        self.residuals: np.ndarray = np.array([], dtype=float)
        self.q_hat: Optional[float] = None
        self.target_coverage: float = self.DEFAULT_TARGET_COVERAGE
        self.calibrated_at: Optional[str] = None
        self.quantiles_cache: Dict[float, float] = {}

    @staticmethod
    def compute_ground_truth_risk(row: Union[pd.Series, Dict[str, Any]]) -> float:
        """
        Compute ground-truth operational risk score y in [0, 100] for calibration telemetry.

        Synthesizes ground-truth operational degradation from:
        1. Ground-truth anomaly label (is_anomaly) if present
        2. Operational SLI threshold breach penalties:
           - error_rate (critical breach >= 3.0%)
           - response_time_p99 (critical breach >= 200ms)
           - cpu_usage (breach >= 80%)
           - memory_usage (breach >= 85%)

        If explicit 'ground_truth_risk' or 'actual_risk' is already in row, returns that.
        """
        if isinstance(row, pd.Series):
            row_dict = row.to_dict()
        else:
            row_dict = row

        if "ground_truth_risk" in row_dict and row_dict["ground_truth_risk"] is not None:
            return round(float(np.clip(float(row_dict["ground_truth_risk"]), 0.0, 100.0)), 2)
        if "actual_risk" in row_dict and row_dict["actual_risk"] is not None:
            return round(float(np.clip(float(row_dict["actual_risk"]), 0.0, 100.0)), 2)

        is_anomaly = float(row_dict.get("is_anomaly", 0.0) or 0.0)
        error_rate = float(row_dict.get("error_rate", 0.0) or 0.0)
        p99 = float(row_dict.get("response_time_p99", 0.0) or 0.0)
        cpu = float(row_dict.get("cpu_usage", 0.0) or 0.0)
        mem = float(row_dict.get("memory_usage", 0.0) or 0.0)

        # SLI breach penalties
        err_penalty = min(30.0, (error_rate / 3.0) * 20.0) if error_rate > 0.5 else (error_rate / 0.5) * 5.0
        p99_penalty = min(25.0, (p99 / 200.0) * 15.0) if p99 > 50.0 else (p99 / 50.0) * 5.0
        cpu_penalty = min(20.0, max(0.0, (cpu - 50.0) / 40.0) * 20.0)
        mem_penalty = min(15.0, max(0.0, (mem - 60.0) / 30.0) * 15.0)

        base_operational_load = (cpu * 0.10) + (mem * 0.05)
        sli_risk = base_operational_load + err_penalty + p99_penalty + cpu_penalty + mem_penalty

        if is_anomaly > 0:
            true_risk = max(70.0, sli_risk + 40.0)
        else:
            true_risk = min(60.0, sli_risk)

        return round(float(np.clip(true_risk, 0.0, 100.0)), 2)

    def calibrate(
        self,
        y_true: Union[np.ndarray, List[float]],
        y_pred: Union[np.ndarray, List[float]],
        target_coverage: float = DEFAULT_TARGET_COVERAGE,
    ) -> Dict[str, Any]:
        """
        Calibrate the conformal predictor using held-out ground truth risk scores and predictions.

        Args:
            y_true: Ground-truth risk scores in [0, 100] on held-out calibration set.
            y_pred: Point risk predictions in [0, 100] from the RiskEngine on held-out calibration set.
            target_coverage: Target marginal coverage level 1 - alpha (e.g. 0.90 for 90%).

        Returns:
            Dictionary summarizing calibration status, sample count, and quantile cutoff.
        """
        y_true_arr = np.asarray(y_true, dtype=float)
        y_pred_arr = np.asarray(y_pred, dtype=float)

        if len(y_true_arr) != len(y_pred_arr):
            raise ValueError(
                f"Length mismatch: y_true ({len(y_true_arr)}) vs y_pred ({len(y_pred_arr)})"
            )

        n = len(y_true_arr)
        self.calibration_samples = n
        self.target_coverage = target_coverage
        self.quantiles_cache.clear()

        # Handle insufficient calibration data explicitly
        if n < self.min_samples:
            self.is_calibrated = False
            self.status = "insufficient_data"
            self.residuals = np.array([], dtype=float)
            self.q_hat = None
            logger.warning(
                f"Insufficient calibration samples: {n} provided, minimum {self.min_samples} required. "
                "Conformal intervals will be marked uncalibrated."
            )
            return {
                "is_calibrated": False,
                "status": self.status,
                "calibration_samples": n,
                "min_required": self.min_samples,
                "q_hat": None,
                "target_coverage": target_coverage,
            }

        # Compute absolute residual nonconformity scores: R_i = |y_i - \hat{y}_i|
        residuals = np.abs(y_true_arr - y_pred_arr)
        # Filter non-finite residuals if any
        valid_mask = np.isfinite(residuals)
        residuals = residuals[valid_mask]
        n_valid = len(residuals)

        if n_valid < self.min_samples:
            self.is_calibrated = False
            self.status = "insufficient_data"
            self.residuals = np.array([], dtype=float)
            self.q_hat = None
            return {
                "is_calibrated": False,
                "status": self.status,
                "calibration_samples": n_valid,
                "min_required": self.min_samples,
                "q_hat": None,
                "target_coverage": target_coverage,
            }

        self.residuals = np.sort(residuals)
        self.is_calibrated = True
        self.status = "calibrated"
        self.calibrated_at = datetime.now(timezone.utc).isoformat()

        # Compute finite-sample conformal quantile for target coverage
        self.q_hat = self.compute_conformal_quantile(target_coverage)

        logger.info(
            f"ConformalCalibrator calibrated on {n_valid} samples. "
            f"Target coverage: {target_coverage*100:.0f}%, q_hat: {self.q_hat:.2f}"
        )

        return {
            "is_calibrated": True,
            "status": self.status,
            "calibration_samples": n_valid,
            "q_hat": self.q_hat,
            "target_coverage": target_coverage,
            "calibrated_at": self.calibrated_at,
        }

    def compute_conformal_quantile(self, target_coverage: float) -> float:
        """
        Compute the finite-sample conformal quantile threshold \hat{q}.

        Formula:
          alpha = 1.0 - target_coverage
          k = min(n, ceil((n + 1) * (1 - alpha)))
          \hat{q} = sorted_residuals[k - 1]
        """
        if not self.is_calibrated or len(self.residuals) == 0:
            raise RuntimeError("Calibrator is not calibrated with sufficient samples.")

        if target_coverage in self.quantiles_cache:
            return self.quantiles_cache[target_coverage]

        n = len(self.residuals)
        alpha = 1.0 - target_coverage
        # Finite-sample order statistic rank (1-indexed)
        k = math.ceil((n + 1) * (1.0 - alpha))
        k = min(n, max(1, k))
        # 0-indexed lookup
        q = float(self.residuals[k - 1])
        q_rounded = round(q, 4)
        self.quantiles_cache[target_coverage] = q_rounded
        return q_rounded

    def predict_interval(
        self,
        point_estimate: float,
        target_coverage: Optional[float] = None,
    ) -> ConformalInterval:
        """
        Generate a conformal risk interval [lower, upper] for a given point prediction.

        Args:
            point_estimate: Point risk score from RiskEngine in [0, 100].
            target_coverage: Target coverage (defaults to self.target_coverage or 0.90).

        Returns:
            ConformalInterval schema object.
        """
        pt = round(float(np.clip(point_estimate, 0.0, 100.0)), 2)
        coverage = target_coverage if target_coverage is not None else self.target_coverage

        # Explicitly handle uncalibrated or insufficient data state
        if not self.is_calibrated or len(self.residuals) < self.min_samples:
            return ConformalInterval(
                point_estimate=pt,
                lower=None,
                upper=None,
                interval_width=None,
                target_coverage=coverage,
                is_calibrated=False,
                status=self.status,
                method=self.METHOD_NAME,
                calibration_samples=self.calibration_samples,
                q_hat=None,
                assumptions_validity_note=self.ASSUMPTION_NOTE,
            )

        q = self.compute_conformal_quantile(coverage)

        # Raw bounds
        raw_lower = pt - q
        raw_upper = pt + q

        # Boundary clipping strictly within valid risk domain [0, 100]
        lower = round(max(0.0, min(100.0, raw_lower)), 2)
        upper = round(max(0.0, min(100.0, raw_upper)), 2)

        # Ensure lower <= upper
        if lower > upper:
            lower = upper

        interval_width = round(upper - lower, 2)

        return ConformalInterval(
            point_estimate=pt,
            lower=lower,
            upper=upper,
            interval_width=interval_width,
            target_coverage=coverage,
            is_calibrated=True,
            status=self.status,
            method=self.METHOD_NAME,
            calibration_samples=len(self.residuals),
            q_hat=round(q, 2),
            assumptions_validity_note=self.ASSUMPTION_NOTE,
        )

    def evaluate_empirical_coverage(
        self,
        y_test: Union[np.ndarray, List[float]],
        y_pred: Union[np.ndarray, List[float]],
        target_coverage: Optional[float] = None,
    ) -> Dict[str, float]:
        """
        Evaluate empirical coverage on held-out test data.

        Returns:
            Dict with 'empirical_coverage', 'target_coverage', 'mean_interval_width'.
        """
        if not self.is_calibrated:
            raise RuntimeError("Calibrator is not calibrated.")

        coverage = target_coverage if target_coverage is not None else self.target_coverage
        y_test_arr = np.asarray(y_test, dtype=float)
        y_pred_arr = np.asarray(y_pred, dtype=float)

        hits = 0
        widths = []
        for yt, yp in zip(y_test_arr, y_pred_arr):
            interval = self.predict_interval(yp, target_coverage=coverage)
            if interval.lower is not None and interval.upper is not None:
                if interval.lower <= yt <= interval.upper:
                    hits += 1
                widths.append(interval.interval_width or 0.0)

        total = len(y_test_arr)
        emp_coverage = round(hits / total, 4) if total > 0 else 0.0
        mean_width = round(float(np.mean(widths)), 2) if widths else 0.0

        return {
            "empirical_coverage": emp_coverage,
            "target_coverage": coverage,
            "mean_interval_width": mean_width,
            "total_evaluated": total,
        }

    def get_status(self) -> Dict[str, Any]:
        """Get calibrator diagnostic status."""
        return {
            "is_calibrated": self.is_calibrated,
            "status": self.status,
            "calibration_samples": len(self.residuals),
            "target_coverage": self.target_coverage,
            "q_hat": self.q_hat,
            "calibrated_at": self.calibrated_at,
            "method": self.METHOD_NAME,
        }
